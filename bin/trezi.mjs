#!/usr/bin/env bun

// `trezi --update`: pull, reinstall and rebuild this checkout, and `trezi logs`. The
// `trezi` command itself is the shell script beside this file (bin/trezi), which runs
// this with the Bun on PATH or the one bundled into Trezi.app. Any other arguments are
// handed to bin/trezi, for installs whose `trezi` link still points here.
import { execFileSync, spawnSync } from 'node:child_process'
import { closeSync, openSync, readSync, realpathSync, statSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { requireSupportedPlatform } from '../scripts/requirements.mjs'

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)))

// Lockfiles are regenerated by the package manager as a side effect of
// `install`, so a checkout that's been built or updated once carries a dirty,
// machine-authored lockfile. That drift makes `git pull --ff-only` abort with
// "local changes would be overwritten by merge" — the exact failure users hit
// running `trezi --update`. Since the update reinstalls right after pulling
// (regenerating the lockfile against the new package.json), it's safe to
// discard the drift first. Kept as a pure helper so it's unit-testable.
const LOCKFILES = new Set([
  'bun.lock',
  'bun.lockb',
  'package-lock.json',
  'npm-shrinkwrap.json',
  'yarn.lock',
  'pnpm-lock.yaml',
])

/**
 * Given `git status --porcelain` output, return the tracked lockfiles that are
 * dirty (staged and/or unstaged) and should be restored to HEAD before a pull.
 * Untracked ('??') entries are ignored — there's nothing at HEAD to restore.
 */
export function lockfilesToRestore(porcelain) {
  const restore = []
  for (const line of String(porcelain).split('\n')) {
    if (line.length < 4) continue
    const status = line.slice(0, 2)
    if (status === '??') continue
    // porcelain paths start at column 3; renames read "old -> new" (not a
    // lockfile concern, but take the post-rename path if it ever occurs).
    const raw = line.slice(3).trim()
    const path = raw.includes(' -> ') ? raw.slice(raw.indexOf(' -> ') + 4) : raw
    if (LOCKFILES.has(path)) restore.push(path)
  }
  return restore
}

/** The Bun on PATH, else the one running this (Trezi's bundled Bun). */
function bun() {
  const check = spawnSync('bun', ['--version'], { stdio: 'ignore' })
  return check.error || check.status !== 0 ? process.execPath : 'bun'
}

function update() {
  requireSupportedPlatform()
  let before
  try {
    before = execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
      cwd: repoRoot,
    })
      .toString()
      .trim()
  } catch {
    console.error('Could not determine current git revision.')
    process.exit(1)
  }

  // Drop machine-generated lockfile drift so `git pull --ff-only` doesn't abort
  // on it; `install` below rebuilds the lockfile against the pulled package.json.
  const status = spawnSync('git', ['status', '--porcelain'], {
    cwd: repoRoot,
    encoding: 'utf8',
  })
  if (status.status === 0) {
    const dirtyLocks = lockfilesToRestore(status.stdout)
    if (dirtyLocks.length > 0) {
      console.log(
        `Discarding local ${dirtyLocks.join(', ')} changes (regenerated on install)…`,
      )
      spawnSync('git', ['checkout', 'HEAD', '--', ...dirtyLocks], {
        cwd: repoRoot,
        stdio: 'inherit',
      })
    }
  }

  const pm = bun()
  const steps = [
    ['git', ['pull', '--ff-only']],
    [pm, ['install']],
    [pm, ['run', 'build']],
  ]

  for (const [cmd, args] of steps) {
    const result = spawnSync(cmd, args, { cwd: repoRoot, stdio: 'inherit' })
    if (result.status !== 0) {
      console.error(
        `Update failed while running \`${cmd === pm ? 'bun' : cmd} ${args.join(' ')}\` (exit code ${result.status}).` +
          (cmd === 'git'
            ? ' If you have local changes, commit or stash them and try again.'
            : ''),
      )
      process.exit(result.status ?? 1)
    }
  }

  const after = execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
    cwd: repoRoot,
  })
    .toString()
    .trim()

  if (before === after) {
    console.log('Trezi is already up to date.')
  } else {
    console.log(`Updated ${before} → ${after}.`)
  }

  console.log('Run `trezi` to (re)start.')
  process.exit(0)
}

/**
 * `trezi logs [--since 30m] [--follow]` (LKM-168): prints Trezi's product log, every
 * process's lines in time order, from ~/Library/Logs/Trezi (TREZI_LOG_DIR overrides
 * it). `--follow` keeps printing new lines until interrupted; it returns the stop.
 */
export async function logs(args, { env = process.env, out = (text) => process.stdout.write(text), err = (text) => process.stderr.write(text), now = Date.now, interval = 500 } = {}) {
  // Loaded here: `--update` must run from a checkout that has only bin/ and scripts/.
  const { logDirectory, logFileName, parseSince, readLogs } = await import('../src/main/product-log.ts')
  let since = 30 * 60_000
  let window = '30m'
  let follow = false
  for (let i = 0; i < args.length; i++) {
    const arg = args[i]
    if (arg === '--follow' || arg === '-f') follow = true
    else if (arg === '--since' || arg.startsWith('--since=')) {
      window = arg === '--since' ? (args[++i] ?? '') : arg.slice(8)
      since = parseSince(window)
    } else throw new Error(`Unknown option for trezi logs: ${arg}\nUsage: trezi logs [--since 30m] [--follow]`)
  }
  const dir = logDirectory(env)
  const lines = readLogs(dir, since, now())
  if (lines.length) out(`${lines.join('\n')}\n`)
  else err(`No Trezi log lines in the last ${window}. Logs are in ${dir}.\n`)
  return follow ? followLogs(dir, out, { now, interval, fileName: logFileName }) : null
}

/** Prints lines appended to today's file (and the next day's) from now on. */
export function followLogs(dir, out, { now = Date.now, interval = 500, fileName }) {
  let name = fileName(now())
  const size = (file) => statSync(join(dir, file), { throwIfNoEntry: false })?.size ?? 0
  let offset = size(name)
  let partial = ''
  const timer = setInterval(() => {
    const current = fileName(now())
    if (current !== name) {
      name = current
      offset = 0
      partial = ''
    }
    const length = size(name)
    if (length < offset) offset = 0
    if (length === offset) return
    const fd = openSync(join(dir, name), 'r')
    try {
      const buffer = Buffer.alloc(length - offset)
      readSync(fd, buffer, 0, buffer.length, offset)
      offset = length
      const text = partial + buffer.toString('utf8')
      const end = text.lastIndexOf('\n')
      partial = text.slice(end + 1)
      if (end >= 0) out(text.slice(0, end + 1))
    } finally {
      closeSync(fd)
    }
  }, interval)
  return () => clearInterval(timer)
}

function main() {
  const args = process.argv.slice(2)
  // --no-launch (older in-app updaters pass it) is accepted and ignored.
  if (args[0] === '--update' || args[0] === 'update') return update()
  if (args[0] === 'logs') {
    return logs(args.slice(1)).then(
      (stop) => {
        if (stop) for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => { stop(); process.exit(0) })
      },
      (error) => { console.error(error.message); process.exitCode = 1 }
    )
  }
  const result = spawnSync(join(repoRoot, 'bin/trezi'), args, { stdio: 'inherit' })
  process.exit(result.status ?? 1)
}

// Run the CLI only when invoked as a script (directly or via a PATH symlink), not
// when imported by a test. realpath both sides so the symlink and its target compare
// equal. Default to running on any error — a real CLI invocation always has a
// resolvable argv[1], so a throw here only happens in edge cases where no-op'ing the
// command would be worse.
function invokedAsScript() {
  try {
    return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))
  } catch {
    return true
  }
}

if (invokedAsScript()) {
  try { main() } catch (error) { console.error(error.message); process.exitCode = 1 }
}
