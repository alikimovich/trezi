import { createHash } from 'node:crypto'
import { basename, join, relative } from 'node:path'
import { type CatalogModule, type Factory, factoryName } from './catalog'
import type { ScannedFile } from './scanner'

/**
 * The preview declarations Trezi writes for a project with no manifest (LKM-276), into
 * its own data (`sidecar.ts`), never the repo. Per module: a registry
 * (`__TreziPreviews_<Module>`) with `content` builders that mirror the SDK's `#Preview`
 * overloads (a SwiftUI `@ViewBuilder` body, or the `PreviewMacroBodyBuilder` of an
 * `NSView` or `NSViewController`) and the list of entries; per source file with
 * previews: a companion file holding one factory per entry, compiled with the file's
 * imports, or, when an entry uses the file's private declarations, an overlay: the
 * original text under `#sourceLocation` with the factories appended, compiled in place
 * of the original. A `#Preview` body is copied verbatim under `#sourceLocation`, so a
 * diagnostic in it points at the original file and line; `@Previewable` declarations
 * become the stored properties of a private wrapper view. The original `#Preview` stays
 * as written and expands as usual. Then the host's `TreziPreviews.swift` lists every
 * module's entries. Pure.
 */
export interface GeneratedBuild {
  /** Generated-folder-relative path → content. */
  files: Record<string, string>
  /** Absolute original → the generated-relative overlay compiled instead. */
  overlays: Record<string, string>
  /** Module → generated-relative files compiled into it. */
  support: Record<string, string[]>
  /** The host's declarations, generated-relative. */
  host: string
  /** Generated-relative file → line ranges (1-based, inclusive) of each entry's code. */
  lines: Record<string, { from: number; to: number; id: string }[]>
}

/** A Swift string literal. */
export function swiftString(text: string): string {
  const named: Record<string, string> = {
    '\\': '\\\\',
    '"': '\\"',
    '\n': '\\n',
    '\r': '\\r',
    '\t': '\\t'
  }
  let escaped = ''
  for (const c of text)
    escaped += named[c] ?? (c.charCodeAt(0) < 0x20 ? `\\u{${c.charCodeAt(0).toString(16)}}` : c)
  return `"${escaped}"`
}

const short = (text: string) => createHash('sha256').update(text).digest('hex').slice(0, 8)
export const registryName = (module: string) => `__TreziPreviews_${module}`

function factoryLines(factory: Factory): string[] {
  const registry = registryName(factory.module)
  const name = factoryName(factory.id)
  const at = (line: number) => `#sourceLocation(file: ${swiftString(factory.file)}, line: ${line})`
  const attributes = ['@available(macOS 14.0, *)', ...factory.availability]
  const lines: string[] = []
  const { body } = factory
  let call: string[]
  if (body.type === 'value') {
    const value = body.wrap === 'swiftUI' ? `SwiftUI.AnyView(${body.expr})` : body.expr
    call = [`    .${body.wrap}(${value})`]
  } else if (body.preview.previewable.length) {
    const wrapper = `__TreziPreviewable_${name.slice('__trezi_'.length)}`
    lines.push(...attributes, `private struct ${wrapper}: SwiftUI.View {`)
    for (const declaration of body.preview.previewable)
      lines.push(at(declaration.line), declaration.text, '#sourceLocation()')
    lines.push('    var body: some SwiftUI.View {')
    if (body.preview.rest)
      lines.push(at(body.preview.rest.line), body.preview.rest.text, '#sourceLocation()')
    lines.push('    }', '}')
    call = [`    ${registry}.content { ${wrapper}() }`]
  } else {
    call = [`    ${registry}.content {`]
    if (body.preview.body)
      call.push(at(body.preview.bodyLine), body.preview.body, '#sourceLocation()')
    call.push('    }')
  }
  lines.push(...attributes, `@MainActor func ${name}() -> ${registry}.Content {`, ...call, '}')
  return wrapConditions(factory.conditions, lines)
}

function wrapConditions(conditions: string[], lines: string[]): string[] {
  return [...conditions.map((c) => `#if ${c}`), ...lines, ...conditions.map(() => '#endif')]
}

function registry(module: string, factories: Factory[]): string {
  const name = registryName(module)
  const entries = factories.flatMap((f) => {
    const size = f.size ? `CGSize(width: ${f.size.width}, height: ${f.size.height})` : 'nil'
    const append = `entries.append(Entry(id: ${swiftString(f.id)}, title: ${swiftString(f.title)}, kind: ${swiftString(f.kind)}, size: ${size}, make: { ${factoryName(f.id)}() }))`
    return wrapConditions(f.conditions, [
      `        if #available(macOS ${f.macOS}, *) {`,
      `            ${append}`,
      '        }'
    ])
  })
  return [
    `// Generated by Trezi for its preview host (module ${module}); never part of the project.`,
    'import AppKit',
    'import DeveloperToolsSupport',
    'import SwiftUI',
    '',
    `enum ${name} {`,
    '    enum Content {',
    '        case swiftUI(SwiftUI.AnyView)',
    '        case view(AppKit.NSView)',
    '        case controller(AppKit.NSViewController)',
    '    }',
    '',
    '    struct Entry {',
    '        let id: String',
    '        let title: String',
    '        let kind: String',
    '        let size: CGSize?',
    '        let make: @MainActor () -> Content',
    '    }',
    '',
    '    @MainActor static func content<V: SwiftUI.View>(@SwiftUI.ViewBuilder _ body: () -> V) -> Content {',
    '        .swiftUI(SwiftUI.AnyView(body()))',
    '    }',
    '',
    '    @available(macOS 14.0, *)',
    '    @MainActor static func content(@DeveloperToolsSupport.PreviewMacroBodyBuilder<AppKit.NSView> _ body: () -> AppKit.NSView) -> Content {',
    '        .view(body())',
    '    }',
    '',
    '    @available(macOS 14.0, *)',
    '    @MainActor static func content(@DeveloperToolsSupport.PreviewMacroBodyBuilder<AppKit.NSViewController> _ body: () -> AppKit.NSViewController) -> Content {',
    '        .controller(body())',
    '    }',
    '',
    '    @MainActor static var entries: [Entry] {',
    '        var entries: [Entry] = []',
    ...entries,
    '        return entries',
    '    }',
    '}',
    ''
  ].join('\n')
}

function hostFile(modules: string[]): string {
  return [
    "// Generated by Trezi: every module's preview entries, for the preview host only.",
    'import AppKit',
    'import SwiftUI',
    ...modules.map((m) => `@testable import ${m}`),
    '',
    'enum TreziPreviews {',
    '    @MainActor static var all: [TreziPreview] {',
    '        var all: [TreziPreview] = []',
    ...modules.flatMap((m) => [
      `        for entry in ${registryName(m)}.entries {`,
      '            all.append(.generated(entry.id, entry.title, kind: entry.kind, size: entry.size) {',
      '                switch entry.make() {',
      '                case .swiftUI(let view): return .swiftUI(view)',
      '                case .view(let view): return .view(view)',
      '                case .controller(let controller): return .controller(controller)',
      '                }',
      '            })',
      '        }'
    ]),
    '        return all',
    '    }',
    '}',
    ''
  ].join('\n')
}

export function generatePreviews(input: {
  root: string
  modules: CatalogModule[]
  factories: Factory[]
  scans: Map<string, ScannedFile>
  /** Reads an original file (overlays copy it). */
  read: (path: string) => string
}): GeneratedBuild {
  const build: GeneratedBuild = {
    files: {},
    overlays: {},
    support: {},
    host: 'TreziPreviews.swift',
    lines: {}
  }
  for (const { module } of input.modules) {
    const own = input.factories.filter((f) => f.module === module)
    const support = [`modules/${module}/${registryName(module)}.swift`]
    build.files[support[0]] = registry(module, own)
    const byFile = new Map<string, Factory[]>()
    for (const f of own) byFile.set(f.file, [...(byFile.get(f.file) ?? []), f])
    for (const [file, factories] of byFile) {
      const rel = relative(input.root, file)
      const stem = basename(file, '.swift')
      const overlay = factories.some((f) => f.overlay)
      const lines: string[] = []
      if (overlay) {
        const text = input.read(file)
        lines.push(
          `#sourceLocation(file: ${swiftString(file)}, line: 1)`,
          ...text.replace(/\n$/, '').split('\n'),
          '#sourceLocation()'
        )
      } else {
        const scan = input.scans.get(file)
        lines.push(`// Generated by Trezi from ${rel}: its previews, compiled beside it.`)
        for (const i of scan?.imports ?? []) lines.push(...wrapConditions(i.conditions, [i.text]))
        if (
          factories.some((f) => f.body.type === 'value' && f.body.wrap === 'swiftUI') &&
          !scan?.imports.some((i) => i.text === 'import SwiftUI')
        )
          lines.push('import SwiftUI')
      }
      lines.push('', `// Generated by Trezi: previews of ${rel}.`)
      const path = overlay
        ? `overlays/${module}/${stem}-${short(rel)}.swift`
        : `modules/${module}/${stem}+TreziPreviews-${short(rel)}.swift`
      const ranges: GeneratedBuild['lines'][string] = []
      for (const factory of factories) {
        const code = factoryLines(factory)
        ranges.push({ from: lines.length + 1, to: lines.length + code.length, id: factory.id })
        lines.push(...code, '')
      }
      build.files[path] = lines.join('\n')
      build.lines[path] = ranges
      if (overlay) build.overlays[file] = path
      else support.push(path)
    }
    build.support[module] = support
  }
  build.files[build.host] = hostFile(input.modules.map((m) => m.module))
  return build
}

const ERROR = /^(.+?):(\d+):(\d+): error: (.*)$/

/**
 * The entries a failed compile's errors point at: an error in generated code by its
 * line ranges, one in an original file inside an entry's `#Preview` by its lines.
 */
export function failedEntries(
  output: string,
  build: GeneratedBuild,
  generatedDir: string,
  factories: Factory[]
): { rejected: Record<string, string>; unmapped: number } {
  const rejected: Record<string, string> = {}
  let unmapped = 0
  const byPath = new Map(
    Object.entries(build.lines).map(([rel, ranges]) => [join(generatedDir, rel), ranges])
  )
  for (const raw of output.split('\n')) {
    const match = ERROR.exec(raw.trimEnd())
    if (!match) continue
    const [, file, lineText, , message] = match
    const line = Number(lineText)
    const generated = byPath.get(file)?.find((r) => line >= r.from && line <= r.to)
    const original = factories.find(
      (f) =>
        f.file === file &&
        f.body.type === 'preview' &&
        line >= f.body.preview.line &&
        line <= f.body.preview.endLine
    )
    const id = generated?.id ?? original?.id
    if (id) rejected[id] ??= `it did not compile: ${message}`
    else unmapped++
  }
  return { rejected, unmapped }
}
